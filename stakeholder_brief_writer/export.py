"""Export utilities for stakeholder-brief-writer.

Produces JSON, Markdown one-pager, and plain-text formats.
"""

from __future__ import annotations

import json
from pathlib import Path

from .models import ExecutiveBrief


def to_json(brief: ExecutiveBrief, path: str | Path | None = None) -> str:
    """Serialise brief to JSON string, optionally write to file."""
    data = brief.to_dict()
    out = json.dumps(data, indent=2)
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out


def to_markdown(brief: ExecutiveBrief, path: str | Path | None = None) -> str:
    """Render brief as a clean one-page Markdown document."""
    lines = []
    lines.append(f"# {brief.title}")
    lines.append("")
    lines.append(f"**Study type:** {brief.study_type}  ")
    lines.append(f"**Participants:** {brief.participant_summary}")
    if brief.key_metrics:
        metric_str = " · ".join(f"{k}: {v}" for k, v in brief.key_metrics.items())
        lines.append(f"**Key metrics:** {metric_str}")
    lines.append("")

    if brief.narrative_summary:
        lines.append("## Summary")
        lines.append("")
        lines.append(brief.narrative_summary)
        lines.append("")

    if brief.research_questions:
        lines.append("## Research Questions")
        lines.append("")
        for q in brief.research_questions:
            lines.append(f"- {q}")
        lines.append("")

    lines.append("## Key Findings")
    lines.append("")
    for i, f in enumerate(brief.top_findings, 1):
        conf_badge = f"[{f.confidence.value.upper()}]"
        scope_badge = f"[{f.impact_scope.value.upper()}]"
        lines.append(f"**{i}. {f.statement}** {conf_badge} {scope_badge}")
        if f.evidence:
            lines.append(f"   *Evidence:* {f.evidence}")
        if f.tags:
            lines.append(f"   *Tags:* {', '.join(f.tags)}")
        lines.append("")

    if brief.recommendations:
        lines.append("## Recommendations")
        lines.append("")
        priority_labels = {1: "High", 2: "Medium", 3: "Low"}
        for r in brief.recommendations:
            label = priority_labels.get(r.priority, "Medium")
            lines.append(f"- **[{label}]** {r.action}")
            if r.rationale:
                lines.append(f"  *Rationale:* {r.rationale}")
            if r.owner_hint:
                lines.append(f"  *Owner:* {r.owner_hint}")
        lines.append("")

    if brief.limitations:
        lines.append("## Limitations")
        lines.append("")
        for lim in brief.limitations:
            lines.append(f"- {lim}")
        lines.append("")

    if brief.next_steps:
        lines.append("## Next Steps")
        lines.append("")
        for ns in brief.next_steps:
            lines.append(f"- {ns}")
        lines.append("")

    lines.append("---")
    lines.append("")
    enrichment_note = (
        f"*LLM-enriched via {brief.llm_model}*" if brief.llm_enriched else "*Rule-based output*"
    )
    lines.append(f"*Generated by stakeholder-brief-writer · CPR Orbital #39 · {enrichment_note}*")

    out = "\n".join(lines)
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out


def to_text(brief: ExecutiveBrief, path: str | Path | None = None) -> str:
    """Render brief as plain text (for pasting into emails/slides)."""
    lines = [brief.title.upper(), "=" * len(brief.title), ""]
    if brief.narrative_summary:
        lines += [brief.narrative_summary, ""]
    lines.append("KEY FINDINGS")
    for i, f in enumerate(brief.top_findings, 1):
        lines.append(f"{i}. {f.statement}")
    lines.append("")
    if brief.recommendations:
        lines.append("RECOMMENDATIONS")
        for r in brief.recommendations:
            lines.append(f"• {r.action}")
    out = "\n".join(lines)
    if path:
        Path(path).write_text(out, encoding="utf-8")
    return out
